import ts from 'typescript';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../..');

/**
 * Write the names a package's `src/index.ts` exports to
 * `__generated__/<packageName>-exports.txt`. With `ownOnly`, only names
 * declared inside the package are listed, leaving out what it re-exports
 * from another package.
 */
export function generatePackageExports(packageName, { ownOnly = false } = {}) {
    const packageDir = path.join(ROOT, 'packages', packageName);
    const configPath = path.join(packageDir, 'tsconfig.json');

    const configFile = ts.readConfigFile(configPath, ts.sys.readFile);
    const parsed = ts.parseJsonConfigFileContent(
        configFile.config,
        ts.sys,
        packageDir
    );

    // Workspace packages resolve to their source, so the result does not
    // depend on whether they have been built.
    const options = {
        ...parsed.options,
        baseUrl: ROOT,
        paths: {
            dockview: ['packages/dockview/src/index.ts'],
            'dockview-core': ['packages/dockview-core/src/index.ts'],
        },
    };
    const program = ts.createProgram(parsed.fileNames, options);
    const checker = program.getTypeChecker();

    const entryFile = path.join(packageDir, 'src/index.ts');
    const sourceFile = program.getSourceFile(entryFile);

    if (!sourceFile) {
        throw new Error(`Could not find source file: ${entryFile}`);
    }

    const symbol = checker.getSymbolAtLocation(sourceFile);

    if (!symbol) {
        throw new Error(`Could not get module symbol for: ${entryFile}`);
    }

    const ownSource = path.join(packageDir, 'src') + path.sep;
    const isOwn = (exported) => {
        const target =
            exported.flags & ts.SymbolFlags.Alias
                ? checker.getAliasedSymbol(exported)
                : exported;
        return (target.declarations ?? []).some((declaration) =>
            path
                .resolve(declaration.getSourceFile().fileName)
                .startsWith(ownSource)
        );
    };

    const exports = checker.getExportsOfModule(symbol);
    const names = exports
        .filter((exported) => !ownOnly || isOwn(exported))
        .map((e) => e.getName())
        .sort();

    const fileName = `${packageName}-exports.txt`;
    const header = [
        '# Auto-generated by scripts/gen/package-exports.mjs',
        '# Do not edit manually. Run `yarn gen` to regenerate.',
        '',
    ].join('\n');

    const output = header + names.join('\n') + '\n';
    const outputPath = path.join(ROOT, '__generated__', fileName);

    fs.writeFileSync(outputPath, output, 'utf-8');

    console.log(`  Wrote ${names.length} exports to __generated__/${fileName}`);
}
